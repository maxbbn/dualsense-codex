import Foundation
import CoreGraphics
// Lifecycle checks without posting keyboard events or requiring a controller.
var hold = HoldState<String, Int>()
precondition(hold.end() == nil)
precondition(hold.begin(owner: "controller-A", destination: 101))
precondition(!hold.begin(owner: "controller-A", destination: 202))
precondition(!hold.begin(owner: "controller-B", destination: 202))
precondition(hold.end(owner: "controller-B") == nil)
precondition(hold.active?.destination == 101)
precondition(hold.end(owner: "controller-A") == 101)
precondition(hold.end(owner: "controller-A") == nil)
// Pause, disconnect, quit and focus loss use the unconditional cleanup path.
precondition(hold.begin(owner: "controller-A", destination: 303))
precondition(hold.end() == 303)
precondition(hold.end() == nil)
precondition(hold.begin(owner: "controller-B", destination: 404))
precondition(hold.end(owner: "controller-B") == 404)
print("Hold lifecycle passed: one press/release, owner isolation, original target, cleanup and reconnect.")

var trigger = TriggerGesture()
precondition(trigger.update(1, allowed: true) == nil) // Connected while held: no send.
precondition(trigger.update(0, allowed: true) == nil)
precondition(trigger.update(0.12, allowed: true) == nil)
precondition(trigger.update(0, allowed: true) == nil) // Ignore resting noise.
precondition(trigger.update(0.4, allowed: true) == nil)
precondition(trigger.update(0.1, allowed: true) == nil)
precondition(trigger.update(0, allowed: true) == .queue)
precondition(trigger.update(0, allowed: true) == nil)
precondition(trigger.update(0.3, allowed: true) == nil)
precondition(trigger.update(0.85, allowed: true) == .immediate)
precondition(trigger.update(0.7, allowed: true) == nil)
precondition(trigger.update(1, allowed: true) == nil)
precondition(trigger.update(0, allowed: true) == nil) // No queue after deep press.
precondition(trigger.update(0.5, allowed: true) == nil)
precondition(trigger.update(0.5, allowed: false) == nil)
precondition(trigger.update(1, allowed: true) == nil) // Focus restored while held.
precondition(trigger.update(0, allowed: true) == nil)
precondition(trigger.update(0.3, allowed: true) == nil)
trigger.cancel()
precondition(trigger.update(0, allowed: true) == nil)
precondition(trigger.update(1, allowed: true) == .immediate)
print("R2 passed: light release, deep press, jitter, one send per squeeze, cancellation and rearming.")

