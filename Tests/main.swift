precondition(StickNavigation.mode(roles: ["AXTextField", "AXGroup"], openedWithOptions: true) == .menu)
precondition(StickNavigation.mode(roles: ["AXMenuItem", "AXMenu"], openedWithOptions: false) == .menu)
